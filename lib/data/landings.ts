export const allLandings = [...services, ...industries]

export function landingPath(l: Landing) {
  return `/${l.kind === 'service' ? 'uslugi' : 'otrasli'}/${l.slug}`
}

export function findLanding(kind: Landing['kind'], slug: string) {
  return (kind === 'service' ? services : industries).find((l) => l.slug === slug)
}

export function landingByPath(path: string) {
  return allLandings.find((l) => landingPath(l) === path)
}
