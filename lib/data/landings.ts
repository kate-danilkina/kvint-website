// Service and industry landing pages for cold and warm traffic.
// Order on the page: direct answer → «Узнаёте себя?» → what it is in plain words → steps →
// proof from cases → price facts → who it is for → FAQ → CTA.
// Only facts confirmed by the founder or by Metrika/Direct data: no invented prices, results or timelines.
// The diagnostic price is shown only on /razbor and /ceny, never here.

export interface Landing {
  slug: string
  kind: 'service' | 'industry'
  navTitle: string
  metaTitle: string
  metaDescription: string
  h1: string
  /** Direct answer in plain words: the first paragraph, quotable by search and AI answers */
  lead: string
  /** One line for hub cards */
  summary: string
  /** Price label for hub cards */
  priceLabel?: string
  /** «Узнаёте себя?» — situations a non-marketer notices */
  symptoms: string[]
  symptomsOutro: string
  explain: { h2: string; text: string[]; terms?: { term: string; def: string }[] }
  steps: { title: string; text: string; get: string }[]
  proof: { h2: string; text: string[]; items?: { value: string; label: string }[]; note?: string }
  /** Optional accent card, e.g. why we know the industry */
  note?: { title: string; text: string }
  facts: { label: string; value: string }[]
  priceNote?: string
  fit: { yes: string[]; no: string[] }
  caseSlugs: string[]
  faq: { q: string; a: string }[]
  ctaTitle?: string
  related: string[]
  /** Price in RUB for schema.org Offer, only when it is fixed and public */
  price?: number
}

